import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import { databaseConfig } from '../src/lib/database-config.mjs';
import { asUser,closeDatabase } from '../src/lib/db';
import { getOnboarding,saveOnboarding } from '../src/lib/onboarding';
import { getPortfolio,updatePortfolio } from '../src/lib/portfolios';
import { PortfolioConflictError } from '../src/lib/portfolio-input';
import { universe } from '../src/lib/companies';
import { ingestResearch,reviewResearch } from '../src/lib/research';
import { fixture,check } from './research-fixture';
const alice=randomUUID(),bob=randomUUID(),empty=randomUUID(),reviewer=randomUUID();
const admin=new pg.Client(databaseConfig(process.env.MIGRATION_DATABASE_URL));
await admin.connect();
try{
 assert.equal((await getOnboarding(alice)).state,null);
 await assert.rejects(saveOnboarding(alice,{action:'complete',version:0}),/Finish/);
 await assert.rejects(saveOnboarding(alice,{action:'companies',version:0,portfolioVersion:0,symbols:[],holdings:[]}),/Choose/);
 assert.equal((await getOnboarding(alice)).state,null,'invalid empty setup rolls back creation');
 let p=await updatePortfolio(alice,{version:0,command:{type:'holding',symbol:'INFY',quantity:'123.123456'}});
 let result=await saveOnboarding(alice,{action:'companies',version:0,portfolioVersion:p.version,symbols:['INFY','TCS'],holdings:[]});
 assert.equal(result.portfolio.entries.find(e=>e.symbol==='INFY')?.quantity,'123.123456','follows preserve quantities');
 assert.equal(result.onboarding.state?.step,'topics');
 await closeDatabase();
 assert.deepEqual(await getOnboarding(alice),result.onboarding,'progress survives a new database pool');
 assert.equal((await getOnboarding(bob)).state,null);
 assert.equal(await asUser(bob,async c=>(await c.query('SELECT * FROM alphatrace.user_onboarding WHERE owner_id=$1',[alice])).rowCount),0);
 assert.equal(await asUser(bob,async c=>(await c.query("UPDATE alphatrace.user_onboarding SET status='skipped' WHERE owner_id=$1",[alice])).rowCount),0);
 await assert.rejects(asUser(bob,c=>c.query("INSERT INTO alphatrace.user_onboarding(owner_id) VALUES($1)",[alice])),/row-level security/);
 const raw=new pg.Client(databaseConfig(process.env.DATABASE_URL));await raw.connect();
 try{assert.equal((await raw.query('SELECT * FROM alphatrace.user_onboarding')).rowCount,0);assert.equal((await raw.query('SELECT * FROM alphatrace.onboarding_monitoring_status()')).rowCount,0);}finally{await raw.end();}
 const monitor=await asUser(bob,async c=>(await c.query('SELECT * FROM alphatrace.onboarding_monitoring_status()')).rows);
 assert.ok(monitor.length);assert.deepEqual(Object.keys(monitor[0]).sort(),['enabled','symbol']);
 assert.equal(await asUser(bob,async c=>(await c.query('SELECT * FROM alphatrace.provider_targets')).rowCount),0,'monitor status does not grant provider table access');
 await assert.rejects(saveOnboarding(alice,{action:'skip',version:0}),PortfolioConflictError);
 p=await updatePortfolio(alice,{version:result.portfolio.version,command:{type:'holding',symbol:'WIPRO',quantity:'9'}});
 await assert.rejects(saveOnboarding(alice,{action:'companies',version:1,portfolioVersion:result.portfolio.version,symbols:['ITC'],holdings:[]}),PortfolioConflictError);
 assert.equal((await getOnboarding(alice)).state?.version,1,'portfolio conflict does not advance setup');
 result=await saveOnboarding(alice,{action:'companies',version:1,portfolioVersion:p.version,symbols:['ITC'],holdings:[{symbol:'INFY',quantity:'10.000001'}],importConfirmed:true});
 assert.equal(result.portfolio.entries.find(e=>e.symbol==='INFY')?.quantity,'10.000001');
 assert.ok(result.portfolio.entries.find(e=>e.symbol==='INFY')?.followed);
 assert.equal(result.portfolio.entries.find(e=>e.symbol==='WIPRO')?.quantity,'9.000000');
 const before=result.portfolio;
 await assert.rejects(saveOnboarding(alice,{action:'companies',version:2,portfolioVersion:before.version,symbols:universe.filter(c=>!['INFY','TCS','ITC'].includes(c.symbol)).slice(0,20).map(c=>c.symbol),holdings:[]}),/20/);
 assert.deepEqual(await getPortfolio(alice),before,'cap failure is atomic');
 const concurrent=await Promise.allSettled([saveOnboarding(alice,{action:'topics',version:2,topics:['revenue']}),saveOnboarding(alice,{action:'topics',version:2,topics:['debt']})]);
 assert.equal(concurrent.filter(r=>r.status==='fulfilled').length,1);
 assert.equal(concurrent.filter(r=>r.status==='rejected'&&r.reason instanceof PortfolioConflictError).length,1);
 result=await saveOnboarding(alice,{action:'complete',version:3});assert.equal(result.onboarding.state?.status,'completed');
 const skipped=await saveOnboarding(empty,{action:'skip',version:0});assert.equal(skipped.onboarding.state?.status,'skipped');assert.equal(skipped.portfolio.entries.length,0);
 const reopened=await saveOnboarding(empty,{action:'restart',version:1});assert.equal(reopened.onboarding.state?.status,'active');
 assert.equal(await asUser(alice,async c=>(await c.query('SELECT * FROM alphatrace.private_research WHERE owner_id=$1',[alice])).rowCount),0,'setup invents no investment thesis');
 await admin.query('INSERT INTO alphatrace.research_operators(user_id) VALUES($1)',[reviewer]);
 const evidence=fixture('SYNTHETIC onboarding '+reviewer),draft=await ingestResearch(reviewer,{draft:evidence,check:check(evidence)});
 assert.ok(!(await getOnboarding(alice)).reviews.some(r=>r.title===evidence.title),'drafts cannot be suggested');
 await reviewResearch(reviewer,{action:'approve',id:draft.draftId,note:'Checked all synthetic fixture values and comparison basis',evidenceConfirmed:true,basisConfirmed:true});
 const publication=await reviewResearch(reviewer,{action:'publish',id:draft.draftId});
 assert.ok((await getOnboarding(alice)).reviews.some(r=>r.id===publication.id));
 assert.equal((await getOnboarding(empty)).reviews.length,0,'only tracked companies are suggested');
 await reviewResearch(reviewer,{action:'withdraw',id:publication.id,note:'Synthetic test withdrawal to verify onboarding exclusion'});
 assert.ok(!(await getOnboarding(alice)).reviews.some(r=>r.symbol==='TCS'),'withdrawal must not reactivate an older publication');
 const bulk=await saveOnboarding(bob,{action:'companies',version:0,portfolioVersion:0,symbols:universe.slice(0,20).map(c=>c.symbol),holdings:[]});
 assert.equal(bulk.portfolio.entries.filter(e=>e.followed).length,20);
 assert.equal(bulk.portfolio.version,1,'bulk selection saves one portfolio revision');
 console.log('PASS: resumable onboarding, exact imports, preserved holdings, account isolation, minimal monitoring exposure, atomic conflicts/caps, completion and skip');
}finally{
 await closeDatabase();await admin.query('BEGIN');
 await admin.query('DELETE FROM alphatrace.workspaces WHERE owner_id=ANY($1::uuid[])',[[alice,bob,empty]]);
 await admin.query('ALTER TABLE alphatrace.research_drafts DISABLE TRIGGER check_research_review');
 await admin.query('UPDATE alphatrace.research_drafts SET published_update_id=NULL WHERE created_by=$1',[reviewer]);
 await admin.query('DELETE FROM alphatrace.research_updates WHERE published_by=$1',[reviewer]);
 await admin.query('DELETE FROM alphatrace.research_drafts WHERE created_by=$1',[reviewer]);
 await admin.query('ALTER TABLE alphatrace.research_drafts ENABLE TRIGGER check_research_review');
 await admin.query('DELETE FROM alphatrace.research_checks WHERE recorded_by=$1',[reviewer]);
 await admin.query('DELETE FROM alphatrace.research_operators WHERE user_id=$1',[reviewer]);
 await admin.query('COMMIT');await admin.end();
}
