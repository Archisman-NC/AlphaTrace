import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import { databaseConfig } from '../src/lib/database-config.mjs';
import { asUser,closeDatabase } from '../src/lib/db';
import { getThesis,saveThesis } from '../src/lib/theses';
import { emptyThesis } from '../src/lib/thesis-input';
import { ingestResearch,reviewResearch,getResearch } from '../src/lib/research';
import { fixture,check } from './research-fixture';
const alice=randomUUID(),bob=randomUUID(),admin=new pg.Client(databaseConfig(process.env.MIGRATION_DATABASE_URL));
await admin.connect();
try{
 const initial={symbol:'HCLTECH',version:0,commandId:randomUUID(),payload:{...emptyThesis(),thesis:'PRIVATE SYNTHETIC thesis '+alice},reason:'Initial synthetic research',confirmed:true};
 assert.equal((await getThesis(alice,'HCLTECH')).version,0);
 const first=await saveThesis(alice,initial);assert.equal(first.version,1);
 assert.equal((await saveThesis(alice,initial)).version,1,'lost-response retry must not append');
 await assert.rejects(saveThesis(alice,{...initial,payload:{...initial.payload,thesis:'Different content'}}),/identifier/);
 assert.equal((await getThesis(bob,'HCLTECH')).current,null);
 assert.equal(await asUser(bob,async c=>(await c.query('SELECT * FROM alphatrace.private_research_revisions WHERE owner_id=$1',[alice])).rowCount),0);
 await assert.rejects(asUser(bob,c=>c.query('INSERT INTO alphatrace.private_research(owner_id,symbol) VALUES ($1,$2)',[alice,'INFY'])),/row-level security/);
 assert.equal(await asUser(bob,async c=>(await c.query('UPDATE alphatrace.private_research SET version=9 WHERE owner_id=$1',[alice])).rowCount),0);
 await assert.rejects(asUser(alice,c=>c.query("UPDATE alphatrace.private_research_revisions SET reason='tampered' WHERE owner_id=$1",[alice])),/permission denied/);
 await assert.rejects(saveThesis(alice,{...initial,commandId:randomUUID(),version:1,payload:{...initial.payload,evidenceIds:[randomUUID()]}}),/published/);
 assert.equal((await getThesis(alice,'HCLTECH')).version,1,'invalid links rollback');
 const writers=await Promise.allSettled(['A','B'].map(s=>saveThesis(alice,{...initial,version:1,commandId:randomUUID(),payload:{...initial.payload,thesis:'Concurrent '+s},reason:'Change from another tab'})));
 assert.equal(writers.filter(r=>r.status==='fulfilled').length,1);assert.equal(writers.filter(r=>r.status==='rejected').length,1);
 await closeDatabase();assert.equal((await getThesis(alice,'HCLTECH')).version,2);
 assert.equal((await getThesis(alice,'HCLTECH')).history.at(-1)?.payload.thesis,initial.payload.thesis);
 // A published fixture tests evidence anchoring and withdrawal without publishing real data.
 await admin.query('INSERT INTO alphatrace.research_operators(user_id) VALUES ($1)',[alice]);
 const p=fixture('SYNTHETIC anchor '+alice);p.symbol='HCLTECH';p.sources.forEach((s,i)=>s.url=`https://www.hcltech.com/synthetic-${i}`);
 const draft=await ingestResearch(alice,{draft:p,check:check(p)});
 await assert.rejects(saveThesis(alice,{...initial,version:2,commandId:randomUUID(),payload:{...initial.payload,evidenceIds:[draft.draftId!]}}),/published/);
 await reviewResearch(alice,{action:'approve',id:draft.draftId,note:'Synthetic evidence fixture inspected',evidenceConfirmed:true,basisConfirmed:true});
 const publication=await reviewResearch(alice,{action:'publish',id:draft.draftId});
 const anchored=await saveThesis(alice,{...initial,version:2,commandId:randomUUID(),payload:{...initial.payload,evidenceIds:[publication.id]},reason:'Link exact synthetic publication'});
 assert.equal(anchored.references[0].id,publication.id);
 await assert.rejects(saveThesis(bob,{...initial,symbol:'INFY',commandId:randomUUID(),payload:{...initial.payload,evidenceIds:[publication.id]}}),/this company/);
 assert.equal((await getResearch(bob,'HCLTECH',false,publication.id)).history.some((r:{id:string})=>r.id===publication.id),true);
 assert.equal(JSON.stringify(await getResearch(bob,'HCLTECH')).includes(initial.payload.thesis),false,'private text must never enter shared research');
 await reviewResearch(alice,{action:'withdraw',id:publication.id,note:'Withdraw synthetic anchor for the test'});
 assert.equal((await getThesis(alice,'HCLTECH')).references[0].withdrawn,true);
 await assert.rejects(saveThesis(alice,{...initial,version:3,commandId:randomUUID(),payload:{...initial.payload,evidenceIds:[publication.id]}}),/withdrawn/);
 for(let version=3;version<22;version++)await saveThesis(alice,{...initial,version,commandId:randomUUID(),reason:`Synthetic history revision ${version+1}`});
 const recent=await getThesis(alice,'HCLTECH');assert.equal(recent.history.length,20);assert.equal(recent.hasMore,true);
 const older=await getThesis(alice,'HCLTECH',recent.history.at(-1)!.version);assert.deepEqual(older.history.map(r=>r.version),[2,1]);assert.equal(older.hasMore,false);
 console.log('PASS: private notes persist, two-user RLS, no shared leakage, immutable revisions, idempotent retry, concurrent conflict, published-version anchors, withdrawn evidence, paginated history');
}finally{
 await closeDatabase();await admin.query('BEGIN');
 await admin.query('ALTER TABLE alphatrace.research_drafts DISABLE TRIGGER check_research_review');
 await admin.query('UPDATE alphatrace.research_drafts SET published_update_id=NULL WHERE created_by=$1',[alice]);
 await admin.query('DELETE FROM alphatrace.research_updates WHERE published_by=$1',[alice]);
 await admin.query('DELETE FROM alphatrace.research_drafts WHERE created_by=$1',[alice]);
 await admin.query('ALTER TABLE alphatrace.research_drafts ENABLE TRIGGER check_research_review');
 await admin.query('DELETE FROM alphatrace.research_checks WHERE recorded_by=$1',[alice]);
 await admin.query('DELETE FROM alphatrace.research_operators WHERE user_id=$1',[alice]);
 await admin.query('DELETE FROM alphatrace.workspaces WHERE owner_id=ANY($1::uuid[])',[[alice,bob]]);
 await admin.query('COMMIT');await admin.end();
}
