import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import { databaseConfig } from '../src/lib/database-config.mjs';
import { asUser,closeDatabase } from '../src/lib/db';
import { ingestResearch,getResearch,reviewResearch } from '../src/lib/research';
import { reviseResearch } from '../src/lib/research-edit';
import { fixture,check } from './research-fixture';
import { spreadsheetMediaType } from '../src/lib/research-contract';
const reviewer=randomUUID(),reader=randomUUID(),time=Date.now();
const admin=new pg.Client(databaseConfig(process.env.MIGRATION_DATABASE_URL));
await admin.connect();
const p=fixture('SYNTHETIC TEST '+reviewer);
try{
 await admin.query('INSERT INTO alphatrace.research_operators(user_id) VALUES ($1)',[reviewer]);
 const workbook=fixture('SYNTHETIC WORKBOOK '+reviewer);workbook.sources=workbook.sources.slice(0,1);
 Object.assign(workbook.sources[0],{mediaType:spreadsheetMediaType,retrieval:'operator_file',kind:'facts',pages:0});
 for(const comparison of workbook.comparisons)for(const point of [comparison.previous,comparison.current])Object.assign(point,{sourceId:workbook.sources[0].id,worksheet:'Financials',cell:'G4'});
 const manual=await ingestResearch(reviewer,{draft:workbook,check:check(workbook,time-2)});
 const replay=await ingestResearch(reviewer,{draft:workbook,check:check(workbook,time-1)});
 assert.equal(replay.draftId,manual.draftId);assert.equal(replay.created,false);
 assert.equal(await asUser(reader,async c=>(await c.query('SELECT id FROM alphatrace.research_drafts WHERE id=$1',[manual.draftId])).rowCount),0);
 await assert.rejects(reviewResearch(reviewer,{action:'approve',id:manual.draftId,note:'Synthetic manual file validation',evidenceConfirmed:true,basisConfirmed:true}),/official results/);
 await assert.rejects(reviewResearch(reviewer,{action:'publish',id:manual.draftId}),/official results/);
 await assert.rejects(ingestResearch(reader,{draft:p,check:check(p)}),/operator access/);
 const one=await ingestResearch(reviewer,{draft:p,check:check(p,time)});assert.ok(one.created);
 const concurrentDraft=await ingestResearch(reviewer,{draft:{...p,title:p.title+' later preparation'},check:check(p,time+1)});
 const repeat=await ingestResearch(reviewer,{draft:p,check:check(p,time+1)});assert.equal(repeat.draftId,one.draftId);assert.equal(repeat.created,false);
 assert.equal(await asUser(reader,async c=>(await c.query('SELECT id FROM alphatrace.research_drafts WHERE id=$1',[one.draftId])).rowCount),0);
 await assert.rejects(getResearch(reader,undefined,true),/operator access/);
 await assert.rejects(reviewResearch(reader,{action:'approve',id:one.draftId,note:'Spoofed review'}),/operator access/);
 await assert.rejects(reviewResearch(reviewer,{action:'publish',id:one.draftId}),/Approve/);
 await assert.rejects(asUser(reviewer,c=>c.query('INSERT INTO alphatrace.research_updates(draft_id,symbol,version,period_end,payload,published_by) VALUES ($1,$2,999999,$3,$4,$5)',[one.draftId,p.symbol,p.periodEnd,JSON.stringify(p),reviewer])),/approved draft/);
 await assert.rejects(reviewResearch(reviewer,{action:'approve',id:one.draftId,note:'Checked synthetic evidence'}),/Confirm/);
 const approve={action:'approve',id:one.draftId,note:'Checked every synthetic value and basis',evidenceConfirmed:true,basisConfirmed:true};
 await reviewResearch(reviewer,approve);
 await ingestResearch(reviewer,{check:{...check(p,time+2),status:'failed',fingerprints:[],message:'SYNTHETIC download failure'}});
 await assert.rejects(reviewResearch(reviewer,{action:'publish',id:one.draftId}),/Recheck/);
 await ingestResearch(reviewer,{check:check(p,time+3)});
 const published=await Promise.all([reviewResearch(reviewer,{action:'publish',id:one.draftId}),reviewResearch(reviewer,{action:'publish',id:one.draftId})]);assert.equal(published[0].id,published[1].id);
 await closeDatabase();
 assert.ok((await getResearch(reader,'TCS')).history.some((u:{id:string})=>u.id===published[0].id));
 const desk=await getResearch(reviewer,'TCS',true);
 const superseded=desk.drafts.find((d:{id:string})=>d.id===manual.draftId);
 assert.equal(superseded.superseded_by,published[0].id);
 assert.equal(superseded.state,'draft','supersession must preserve the stored review state');
 assert.equal(superseded.review_note,null,'do not invent a rejection or review');
 assert.equal(desk.drafts.find((d:{id:string})=>d.id===concurrentDraft.draftId).superseded_by,null,'a draft prepared after the published draft remains actionable even if prepared before publication');
 for(const action of ['approve','publish','reject'])await assert.rejects(reviewResearch(reviewer,{...approve,action,id:manual.draftId}),/superseded/);
 await assert.rejects(asUser(reviewer,c=>c.query('UPDATE alphatrace.research_updates SET payload=$1 WHERE id=$2',[JSON.stringify({...p,title:'tampered'}),published[0].id])),/permission denied/);
 assert.equal(await asUser(reader,async c=>(await c.query('UPDATE alphatrace.research_updates SET withdrawn_at=now(),withdrawal_reason=$1 WHERE id=$2',['Spoofed withdrawal',published[0].id])).rowCount),0);
 const corrected={...p,title:p.title+' corrected'};
 await ingestResearch(reviewer,{check:check(corrected,time+4)});
 const revision=await reviseResearch(reviewer,{id:one.draftId,payload:corrected,reason:'Correcting the synthetic published title without changing original evidence'});
 const two={draftId:revision.id};
 assert.equal((await getResearch(reviewer,'TCS',true)).drafts.find((d:{id:string})=>d.id===two.draftId).state,'draft');
 await reviewResearch(reviewer,{...approve,id:two.draftId});
 const next=await reviewResearch(reviewer,{action:'publish',id:two.draftId});
 const history=(await getResearch(reader,'TCS')).history;
 assert.equal(history.find((u:{id:string})=>u.id===next.id).supersedes,published[0].id);
 assert.equal((await getResearch(reviewer,'TCS',true)).drafts.find((d:{id:string})=>d.id===concurrentDraft.draftId).superseded_by,next.id);
 await reviewResearch(reviewer,{action:'withdraw',id:next.id,note:'Synthetic withdrawal verifies audit history'});
 assert.equal((await getResearch(reader,'TCS')).catalog.find((c:{symbol:string})=>c.symbol==='TCS').status,'withdrawn');
 assert.equal((await getResearch(reviewer,'TCS',true)).drafts.find((d:{id:string})=>d.id===manual.draftId).superseded_by,next.id,'withdrawal does not silently reactivate old drafts');
 console.log('PASS: operator RLS, hidden drafts, idempotent ingestion, approval enforcement, failed-check gate, concurrent publication, durable versions, immutable evidence, correction and withdrawal');
}finally{
 await closeDatabase();
 await admin.query('BEGIN');
 await admin.query('DELETE FROM alphatrace.research_revisions WHERE created_by=$1',[reviewer]);
 // Only this run’s fixtures are removed, including circular publication references.
 await admin.query('ALTER TABLE alphatrace.research_drafts DISABLE TRIGGER check_research_review');
 await admin.query('UPDATE alphatrace.research_drafts SET published_update_id=NULL WHERE created_by=$1',[reviewer]);
 await admin.query('DELETE FROM alphatrace.research_updates WHERE published_by=$1',[reviewer]);
 await admin.query('DELETE FROM alphatrace.research_drafts WHERE created_by=$1',[reviewer]);
 await admin.query('ALTER TABLE alphatrace.research_drafts ENABLE TRIGGER check_research_review');
 await admin.query('DELETE FROM alphatrace.research_checks WHERE recorded_by=$1',[reviewer]);
 await admin.query('DELETE FROM alphatrace.research_operators WHERE user_id=$1',[reviewer]);
 await admin.query('COMMIT');await admin.end();
}
